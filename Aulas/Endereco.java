package Aulas;
public class Endereco {

    String nl;
    int numero;
    String bairro;
    String estado;
    String cidade;


    Endereco(String nl, int numero, String bairro, String estado, String cidade){
        this.nl = nl;
        this.numero = numero;
        this.bairro = bairro;
        this.estado = estado;
        this.cidade = cidade;
    }
    
}
